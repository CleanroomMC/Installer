package com.cleanroommc.installer.target.server;

import java.util.List;


public final class ArgFiles {

    public static String argsFile(List<String> jvmArgs, String classpath, String mainClass, List<String> gameArgs) {
        String sep = System.lineSeparator();
        StringBuilder builder = new StringBuilder();
        for (String arg : jvmArgs) {
            builder.append(arg).append(sep);
        }
        builder.append("-cp").append(sep);
        builder.append(classpath).append(sep);
        builder.append(mainClass).append(sep);
        for (String arg : gameArgs) {
            builder.append(arg).append(sep);
        }
        return builder.toString();
    }

    public static String userJvmArgs(String memory) {
        return "# Arguments here are passed to the JVM, one per line. Lines starting with # are ignored."
                + System.lineSeparator()
                + "# Raise this if the server runs out of memory."
                + System.lineSeparator()
                + "-Xmx" + memory
                + System.lineSeparator();
    }

    public static String runSh(String javaCommand, String argsPath, int minimumJava, int maximumJava) {
        String requirement = requirement(minimumJava, maximumJava);
        String test = "[ \"$MAJOR\" -lt " + minimumJava + " ]";
        if (maximumJava > 0) {
            test += " || [ \"$MAJOR\" -gt " + maximumJava + " ]";
        }
        return "#!/usr/bin/env sh"
                + "\n# Generated by the Cleanroom Installer. Edit user_jvm_args.txt, not this file.\n"
                + "\nJAVA=\"" + javaCommand + "\"\n"
                + "\nMAJOR=$(\"$JAVA\" -version 2>&1 | head -n 1 | sed -E 's/.*version \"([0-9]+).*/\\1/')\n"
                + "if [ -n \"$MAJOR\" ] && { " + test + "; } 2>/dev/null; then\n"
                + "  echo \"Cleanroom needs " + requirement + ", but $JAVA is Java $MAJOR.\" >&2\n"
                + "  echo \"Set JAVA to a supported runtime, or re-run the installer with --pin-java.\" >&2\n"
                + "  exit 1\n"
                + "fi\n"
                + "\n\"$JAVA\" @user_jvm_args.txt @" + argsPath + " \"$@\"\n";
    }

    private static String requirement(int minimumJava, int maximumJava) {
        if (maximumJava <= 0) {
            return "Java " + minimumJava + " or newer";
        }
        if (maximumJava == minimumJava) {
            return "Java " + minimumJava;
        }
        return "Java " + minimumJava + " to " + maximumJava;
    }

    public static String runBat(String javaCommand, String argsPath, int minimumJava, int maximumJava) {
        return "@echo off\r\n"
                + "rem Generated by the Cleanroom Installer. Edit user_jvm_args.txt, not this file.\r\n"
                + "set JAVA=" + javaCommand + "\r\n"
                + "\r\n"
                + "\"%JAVA%\" -version 1>nul 2>nul || (\r\n"
                + "  echo Java was not found on this machine. Cleanroom needs " + requirement(minimumJava, maximumJava) + ".\r\n"
                + "  exit /b 1\r\n"
                + ")\r\n"
                + "\r\n"
                + "\"%JAVA%\" @user_jvm_args.txt @" + argsPath + " %*\r\n"
                + "if \"%ERRORLEVEL%\" NEQ \"0\" pause\r\n";
    }

    private ArgFiles() { }

}
